    private void emailTextFieldFocusGained(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_emailTextFieldFocusGained
        // TODO add your handling code here:
        if (emailTextField.getText().equals("Enter email")) {
            emailTextField.setText("");
            emailTextField.setForeground(new Color(102, 102, 102));
        }
    }//GEN-LAST:event_emailTextFieldFocusGained

    private void emailTextFieldFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_emailTextFieldFocusLost
        // TODO add your handling code here:
        if (emailTextField.getText().equals("")) {
            emailTextField.setText("Enter email");
            emailTextField.setForeground(new Color(102, 102, 102));
        }
    }//GEN-LAST:event_emailTextFieldFocusLost

    private void PasswordFieldFocusGained(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_PasswordFieldFocusGained
        // TODO add your handling code here: PasswordField
        if (String.valueOf(PasswordField.getPassword()).equals("Enter password")) {
            PasswordField.setText("");
            PasswordField.setForeground(new Color(102, 102, 102));
            PasswordField.setEchoChar('●');
        }
    }//GEN-LAST:event_PasswordFieldFocusGained

    private void PasswordFieldFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_PasswordFieldFocusLost
        // TODO add your handling code here:
        if (PasswordField.getPassword().length < 1) {
            PasswordField.setEchoChar((char)0);
            PasswordField.setText("Enter password");
            PasswordField.setForeground(new Color(102, 102, 102));
        }
    }//GEN-LAST:event_PasswordFieldFocusLost

    private void showCheckBoxActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_showCheckBoxActionPerformed
        // TODO add your handling code here:showCheckBox
        if(showCheckBox.isSelected()) {
            PasswordField.setEchoChar((char)0);
        }
        else {
            PasswordField.setEchoChar('●');
        }
    }//GEN-LAST:event_showCheckBoxActionPerformed


